logger = logging.getLogger("regradar.integrations.gitlab_webhook")


def verify_gitlab_token(token_header: Optional[str], secret: str) -> bool:
    """
    Validates the GitLab X-Gitlab-Token header.
    In development mode (empty secret), verification passes.
    """
    if not secret:
        return True
    if not token_header:
        return False
    return token_header.strip() == secret.strip()


def dispatch_gitlab_mr_note(
    repo: str,
    mr_iid: int,
    decision: str,
    reviewer: str,
    comment: Optional[str] = None,
    gitlab_token: Optional[str] = None,
    gitlab_url: str = "https://gitlab.com",
) -> Dict[str, Any]:
    """
    Posts a review note or discussion to a GitLab Merge Request via REST API.
    Zero external dependencies, using urllib.
    """
    token = gitlab_token or os.environ.get("GITLAB_TOKEN") or os.environ.get("GITLAB_PRIVATE_TOKEN")
    if not token:
        logger.info(
            "No GITLAB_TOKEN configured; skipping remote GitLab API note dispatch for %s!%d",
            repo,
            mr_iid,
        )
        return {"dispatched": False, "reason": "No GITLAB_TOKEN configured"}

    verdict_text = f"### RegRadar Zero-Destruction Gate Verdict: {decision.upper()}\n\n"
    verdict_text += f"- **Operator**: `{reviewer}`\n"
    verdict_text += f"- **Decision**: `{decision.upper()}`\n"
    if comment:
        verdict_text += f"- **Operator Notes**: {comment}\n"
    verdict_text += "\n*Audited by RegRadar Autonomous IaC Governance Engine.*"

    project_encoded = urllib.parse.quote_plus(repo)
    api_endpoint = f"{gitlab_url.rstrip('/')}/api/v4/projects/{project_encoded}/merge_requests/{mr_iid}/notes"
    headers = {
        "PRIVATE-TOKEN": token,
        "Content-Type": "application/json",
        "User-Agent": "RegRadar-Governance-Gate",
    }
    body_bytes = json.dumps({"body": verdict_text}).encode("utf-8")

    req = urllib.request.Request(api_endpoint, data=body_bytes, headers=headers, method="POST")
    try:
        with urllib.request.urlopen(req, timeout=15) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            return {"dispatched": True, "note_id": data.get("id"), "status_code": resp.status}
    except urllib.error.HTTPError as e:
        err_msg = e.read().decode("utf-8", errors="ignore")
        logger.warning("GitLab API note dispatch failed with HTTP %d: %s", e.code, err_msg)
        return {"dispatched": False, "error": f"HTTP {e.code}: {err_msg}", "status_code": e.code}
    except Exception as e:
        logger.warning("Failed to dispatch note to GitLab: %s", e)
        return {"dispatched": False, "error": str(e)}


class GitLabWebhookHandler:
    """Processes incoming GitLab webhooks, verifies invariants, and stages MRs."""

    def __init__(self):
        self.db = get_governance_db()
        self.gatekeeper = PRGatekeeper()

    @staticmethod
    def is_agent_actor(author: str, title: str = "", description: str = "") -> bool:
        """Determines if a Merge Request was generated by an AI agent or automated bot."""
        author_lower = author.lower()
        if "bot" in author_lower or "agent" in author_lower or "remediation" in author_lower:
            return True
        title_lower = title.lower()
        if "[regradar" in title_lower or "remediation" in title_lower or "compliance" in title_lower:
            return True
        desc_lower = description.lower()
        if "regradar" in desc_lower or "ai agent" in desc_lower:
            return True
        return False

    def handle_payload(
        self,
        event_header: Optional[str],
        payload: Dict[str, Any],
        token_header: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Main dispatcher for GitLab webhook events."""
        cfg = get_config()
        secret = os.environ.get("GITLAB_WEBHOOK_SECRET") or os.environ.get("REGRADAR_GITLAB_WEBHOOK_SECRET", "")

        if secret and not verify_gitlab_token(token_header, secret):
            return {
                "status": "error",
                "message": "Invalid X-Gitlab-Token authentication header",
                "code": 401,
            }

        object_kind = payload.get("object_kind") or ""
        event_name = event_header or object_kind

        if event_name in ("Merge Request Hook", "merge_request") or object_kind == "merge_request":
            return self._handle_merge_request(payload)

        elif event_name in ("Push Hook", "push") or object_kind == "push":
            return self._handle_push(payload)

        elif event_name == "ping" or payload.get("event_type") == "ping":
            return {
                "status": "success",
                "message": "GitLab Webhook ping acknowledged",
                "timestamp": datetime.now(timezone.utc).isoformat(),
            }

        return {
            "status": "ignored",
            "message": f"GitLab event '{event_name}' does not trigger governance gating.",
        }

    def _handle_merge_request(self, payload: Dict[str, Any]) -> Dict[str, Any]:
        attrs = payload.get("object_attributes", {})
        action = attrs.get("action", "open")
        if action not in ("open", "reopen", "update", "synchronize", ""):
            return {
                "status": "ignored",
                "message": f"MR action '{action}' does not require safety gate evaluation.",
            }

        project = payload.get("project", {})
        repo_name = project.get("path_with_namespace") or attrs.get("target", {}).get("path_with_namespace", "gitlab/repo")
        mr_iid = attrs.get("iid", 1)
        title = attrs.get("title", f"Merge Request !{mr_iid}")
        description = attrs.get("description", "")
        author = payload.get("user", {}).get("username") or attrs.get("last_commit", {}).get("author", {}).get("name", "unknown")
        source_branch = attrs.get("source_branch", "remediation/fix")
        target_branch = attrs.get("target_branch", "main")
        mr_url = attrs.get("url") or f"{project.get('web_url', 'https://gitlab.com')}/-/merge_requests/{mr_iid}"

        is_agent = self.is_agent_actor(author=author, title=title, description=description)

        cfg = get_config()
        evaluation: PRGateEvaluation = self.gatekeeper.evaluate(
            target_dir=cfg.workspace.root,
            simulate_sandbox=False,
            synthesize_patches=False,
        )

        risk_tier = RiskTier.LEAF_SAFE.value
        if evaluation.blast_radius_summary and evaluation.blast_radius_summary.root_resources:
            risk_tier = RiskTier.CRITICAL_ROOT.value

        requires_human = (
            cfg.github.require_human_signoff
            and (is_agent or risk_tier in (RiskTier.CRITICAL_ROOT.value, RiskTier.INTERMEDIATE.value))
        )
        status = "AWAITING_HUMAN_APPROVAL" if requires_human else "AUTO_PASSED"

        staged_id = f"mr-{mr_iid}"
        staged = StagedPR(
            id=staged_id,
            provider="gitlab",
            pr_number=mr_iid,
            repo=repo_name,
            title=title,
            author=author,
            head_branch=source_branch,
            base_branch=target_branch,
            is_agent_pr=is_agent,
            status=status,
            risk_tier=risk_tier,
            invariant_verdict=evaluation.invariant_verdict,
            destructive_changes_count=len(evaluation.destructive_changes),
            summary_markdown=evaluation.summary_markdown,
            pr_url=mr_url,
            evaluation=evaluation.model_dump(),
        )

        self.db.upsert_pr(staged.model_dump())
        try:
            WebhookDispatcher.dispatch_event("pr.staged", staged.model_dump())
        except Exception:
            pass

        logger.info(
            "Staged GitLab MR !%d from %s (Agent=%s, Risk=%s, Status=%s)",
            mr_iid,
            author,
            is_agent,
            risk_tier,
            status,
        )

        return {
            "status": "success",
            "action": "staged",
            "provider": "gitlab",
            "pr": staged.model_dump(),
            "requires_human_signoff": requires_human,
        }

    def _handle_push(self, payload: Dict[str, Any]) -> Dict[str, Any]:
        project = payload.get("project", {})
        repo = project.get("path_with_namespace", "gitlab/repo")
        ref = payload.get("ref", "")
        commits = payload.get("commits", [])
        return {
            "status": "success",
            "provider": "gitlab",
            "action": "push_audited",
            "repo": repo,
            "ref": ref,
            "commits_count": len(commits),
        }

    def simulate_event(
        self,
        repo: str = "gitlab-org/cloud-infra",
        title: str = "[RegRadar Agent] Enforce S3 Encryption & Zero-Destruction Gate",
        author: str = "regradar-remediation-bot",
        head_branch: str = "agent/fix-s3-ckv-aws-19",
        risk_tier: str = "LEAF_SAFE",
        is_agent: bool = True,
    ) -> StagedPR:
        """Simulates an incoming GitLab Merge Request webhook for validation."""
        existing_prs = self.db.list_prs()
        mr_iid = len(existing_prs) + 201
        staged_id = f"mr-{mr_iid}"

        markdown = (
            f"### RegRadar Zero-Destruction MR Review (GitLab Simulated)\n\n"
            f"- **Repository**: `{repo}` (GitLab)\n"
            f"- **Author**: `{author}` {'(AI Agent)' if is_agent else '(Human Developer)'}\n"
            f"- **Risk Tier**: `{risk_tier}`\n"
            f"- **Invariant Verdict**: **PASS** (0 destructions detected)\n"
            f"- **Human Intervention**: {'Required - Awaiting Operator Sign-Off' if is_agent or risk_tier == 'CRITICAL_ROOT' else 'Auto-Passed'}\n"
        )

        cfg = get_config()
        requires_human = cfg.github.require_human_signoff and (
            is_agent or risk_tier in (RiskTier.CRITICAL_ROOT.value, RiskTier.INTERMEDIATE.value)
        )
        status = "AWAITING_HUMAN_APPROVAL" if requires_human else "AUTO_PASSED"

        staged = StagedPR(
            id=staged_id,
            provider="gitlab",
            pr_number=mr_iid,
            repo=repo,
            title=title,
            author=author,
            head_branch=head_branch,
            base_branch="main",
            is_agent_pr=is_agent,
            status=status,
            risk_tier=risk_tier,
            invariant_verdict="PASS",
            destructive_changes_count=0,
            summary_markdown=markdown,
            pr_url=f"https://gitlab.com/{repo}/-/merge_requests/{mr_iid}",
        )

        self.db.upsert_pr(staged.model_dump())
        return staged
