def test_dispatch_github_pr_review_with_token(monkeypatch):
    import urllib.request
    from unittest.mock import MagicMock
    from regradar.integrations.github_webhook import dispatch_github_pr_review

    mock_resp = MagicMock()
    mock_resp.read.return_value = json.dumps({"html_url": "https://github.com/org/repo/pull/1#pullrequestreview-1"}).encode("utf-8")
    mock_resp.status = 200
    mock_resp.__enter__.return_value = mock_resp

    monkeypatch.setattr(urllib.request, "urlopen", lambda req, timeout=15: mock_resp)

    res = dispatch_github_pr_review("org/repo", 1, "APPROVE", "alice", "Looks good", github_token="ghp_testtoken123")
    assert res["dispatched"] is True
    assert "pullrequestreview-1" in res["url"]


def test_store_disk_persistence(tmp_path):
    pfile = tmp_path / "test_staged_prs.json"
    store = GitHubPRStore(persistence_file=pfile)
    assert len(store.list_prs()) == 0

    pr = StagedPR(id="pr-test-1", pr_number=1, repo="org/test", title="Test PR")
    store.stage_pr(pr)
    assert pfile.is_file()

    # Load in new instance
    store2 = GitHubPRStore(persistence_file=pfile)
    assert len(store2.list_prs()) == 1
    assert store2.get_pr("pr-test-1").title == "Test PR"
