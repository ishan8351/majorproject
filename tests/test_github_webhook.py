def test_operator_review_flow(client: TestClient):
    # List PRs to get sample
    list_resp = client.get("/api/webhooks/github/prs")
    assert list_resp.status_code == 200
    prs = list_resp.json()
    assert len(prs) >= 2

    target_pr = prs[0]
    pr_id = target_pr["id"]

    # Operator approves PR
    review_resp = client.post(
        f"/api/webhooks/github/prs/{pr_id}/review",
        json={
            "decision": "APPROVE",
            "reviewer": "alice_secops",
            "comment": "Verified non-destructive zero blast radius in sandbox. Ready to apply.",
        },
    )
    assert review_resp.status_code == 200
    rev_data = review_resp.json()
    assert rev_data["action"] == "pr_approved"
    assert rev_data["pr"]["status"] == "APPROVED"
    assert rev_data["pr"]["reviewed_by"] == "alice_secops"

    # Operator requests revision on second PR
    target_pr_2 = prs[1]
    rev_resp_2 = client.post(
        f"/api/webhooks/github/prs/{target_pr_2['id']}/review",
        json={
            "decision": "REVISE",
            "reviewer": "bob_lead",
            "comment": "Please reduce CIDR block scope before merging.",
        },
    )
    assert rev_resp_2.status_code == 200
    assert rev_resp_2.json()["pr"]["status"] == "REVISION_REQUESTED"


