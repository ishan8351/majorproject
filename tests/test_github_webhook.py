def test_verify_github_signature():
    secret = "test-secret-key-12345"
    payload = b'{"action": "ping"}'
    valid_sig = "sha256=" + hmac.new(secret.encode(), payload, hashlib.sha256).hexdigest()
    invalid_sig = "sha256=baddeadbeef000000000000000000000"

    assert verify_github_signature(payload, valid_sig, secret) is True
    assert verify_github_signature(payload, invalid_sig, secret) is False
    assert verify_github_signature(payload, None, secret) is False
    assert verify_github_signature(payload, "invalid_prefix", secret) is False
    # Dev mode (empty secret) passes
    assert verify_github_signature(payload, None, "") is True


