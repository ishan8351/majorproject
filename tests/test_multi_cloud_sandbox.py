def test_mock_provider_hcl_templates():
    """Verifies that mock HCL blocks contain required flags for credentials skip."""
    # AWS
    aws_hcl = get_mock_provider_hcl("aws")
    assert 'provider "aws"' in aws_hcl
    assert "skip_credentials_validation = true" in aws_hcl
    assert "skip_requesting_account_id  = true" in aws_hcl
    assert "skip_metadata_api_check     = true" in aws_hcl

    # Azure
    azure_hcl = get_mock_provider_hcl("azurerm")
    assert 'provider "azurerm"' in azure_hcl
    assert "features {}" in azure_hcl
    assert "skip_provider_registration = true" in azure_hcl
    assert "subscription_id" in azure_hcl
    assert "client_id" in azure_hcl

    # GCP
    gcp_hcl = get_mock_provider_hcl("google")
    assert 'provider "google"' in gcp_hcl
    assert 'project                     = "mock-project"' in gcp_hcl
    assert "skip_credentials_validation = true" in gcp_hcl
    assert 'region                      = "us-central1"' in gcp_hcl

    # Kubernetes
    k8s_hcl = get_mock_provider_hcl("kubernetes")
    assert 'provider "kubernetes"' in k8s_hcl
    assert 'host                   = "http://localhost:8080"' in k8s_hcl
    assert "client_certificate" in k8s_hcl


