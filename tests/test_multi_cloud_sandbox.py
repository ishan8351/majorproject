def test_detect_providers_from_resources():
    """Tests provider detection from discovered resource objects."""
    resources = [
        TerraformResource(
            id="aws_s3_bucket.b",
            resource_type="aws_s3_bucket",
            name="b",
            file_path="main.tf",
        ),
        TerraformResource(
            id="azurerm_storage_account.sa",
            resource_type="azurerm_storage_account",
            name="sa",
            file_path="storage.tf",
        ),
    ]

    detected = detect_required_providers(resources=resources)
    assert "aws" in detected
    assert "azurerm" in detected
    assert "google" not in detected


def test_detect_providers_from_files():
    """Tests provider detection by inspecting HCL file contents on disk."""
    with tempfile.TemporaryDirectory() as tmp_dir:
        tmp_path = Path(tmp_dir)
        (tmp_path / "gcp_vpc.tf").write_text(
            'resource "google_compute_network" "vpc" {\n  name = "test-vpc"\n}\n',
            encoding="utf-8",
        )
        (tmp_path / "k8s_ns.tf").write_text(
            'resource "kubernetes_namespace" "ns" {\n  metadata {\n    name = "app"\n  }\n}\n',
            encoding="utf-8",
        )

        detected = detect_required_providers(directory=tmp_path)
        assert "google" in detected
        assert "kubernetes" in detected
        assert "aws" not in detected


def test_detect_providers_fallback_to_aws():
    """Verifies that an empty directory defaults to AWS provider."""
    with tempfile.TemporaryDirectory() as tmp_dir:
        detected = detect_required_providers(directory=tmp_dir)
        assert detected == {"aws"}


def test_write_mock_override_file():
    """Tests writing the _regradar_mock_override.tf file to disk."""
    with tempfile.TemporaryDirectory() as tmp_dir:
        override_path = write_mock_override_file(
            directory=tmp_dir,
            providers=["azurerm", "google"],
        )
        assert override_path.is_file()
        assert override_path.name == "_regradar_mock_override.tf"
        content = override_path.read_text(encoding="utf-8")
        assert 'provider "azurerm"' in content
        assert 'provider "google"' in content
        assert 'provider "aws"' not in content


