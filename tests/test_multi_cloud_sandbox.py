def test_diagnose_failure_provider_plugin_missing():
    """Tests diagnostic classification for missing provider plugins."""
    error_output = (
        "Initializing provider plugins...\n"
        "- Finding hashicorp/azurerm versions matching ~> 3.0...\n"
        "Error: Failed to query available provider packages\n"
        "Could not retrieve provider \"hashicorp/azurerm\": provider registry.terraform.io/hashicorp/azurerm is not available"
    )
    diag = diagnose_failure("init", 1, "", error_output)
    assert diag.category == SandboxErrorCategory.PROVIDER_PLUGIN_MISSING
    assert diag.is_provider_missing is True
    assert diag.is_syntax_error is False
    assert "azurerm" in diag.missing_providers


def test_diagnose_failure_syntax_error():
    """Tests diagnostic classification for HCL syntax and block definition errors."""
    error_output = (
        "Error: Argument or block definition required\n"
        "on main.tf line 4, in resource \"aws_s3_bucket\" \"b\":\n"
        "An argument or block definition is required here."
    )
    diag = diagnose_failure("validate", 1, "", error_output)
    assert diag.category == SandboxErrorCategory.SYNTAX_ERROR
    assert diag.is_syntax_error is True
    assert diag.is_provider_missing is False
    assert len(diag.syntax_details) > 0


def test_diagnose_failure_binary_not_found():
    """Tests diagnostic classification when binary is missing."""
    diag = diagnose_failure("init", 127, "", "Binary 'tofu' not found")
    assert diag.category == SandboxErrorCategory.BINARY_NOT_FOUND
    assert diag.is_binary_missing is True


